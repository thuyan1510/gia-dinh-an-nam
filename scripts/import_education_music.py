"""Import only the ten explicitly licensed recordings in the reviewed manifest.
Original downloads live in a disposable /tmp directory; no account/API keys.
Outputs bundled AAC and provenance, including original and converted SHA-256.
"""
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile
import urllib.parse
import urllib.request
import urllib.error
import time

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'src/data/education'
OUT = ROOT / 'assets/education'
OUT.mkdir(parents=True, exist_ok=True)
rows = json.loads((DATA / 'music-sources.json').read_text())
result = json.loads((DATA / 'music.json').read_text()) if (DATA / 'music.json').exists() else []
for row in rows:
    prior = next((r for r in result if r['id'] == row['id']), None)
    dest = OUT / (row['id'] + '.m4a')
    if prior and dest.exists() and hashlib.sha256(dest.read_bytes()).hexdigest() == prior['sha256']:
        continue
    result = [r for r in result if r['id'] != row['id']]
    with tempfile.TemporaryDirectory(prefix='an-nam-music-', dir='/tmp') as folder:
        raw = Path(folder) / 'source.audio'
        # Use Commons' published, smaller MP3 rendition for the large remaining
        # Ogg recordings. This is not an inferred private/CDN URL: Commons exposes
        # these in its Transcode status section. Retain exact acquisition URL.
        download = row['download']
        if row['id'] in ['moonlight', 'canon', 'prelude']:
            download = download.replace('/commons/', '/commons/transcoded/') + '/' + download.rsplit('/', 1)[1] + '.mp3'
        request = urllib.request.Request(download, headers={'User-Agent': 'AnNamOfflineLibrary/1.0 (personal family app; source attribution included)'})
        for attempt in range(5):
            try:
                response = urllib.request.urlopen(request, timeout=60)
                break
            except urllib.error.HTTPError as error:
                if error.code != 429 or attempt == 4:
                    raise
                print('Rate limited; waiting before retry', row['id'], flush=True)
                time.sleep(min(60, 20 * (attempt + 1)))
        with response, raw.open('wb') as target:
            total = 0
            while block := response.read(65536):
                total += len(block)
                if total > 50_000_000:
                    raise ValueError('Unexpectedly large source')
                target.write(block)
        dest = OUT / (row['id'] + '.m4a')
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(raw), '-vn', '-map_metadata', '-1', '-c:a', 'aac', '-b:a', '96k', '-movflags', '+faststart', str(dest)], check=True)
        duration = float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'default=noprint_wrappers=1:nokey=1', str(dest)]))
        if not 30 < duration < 1200:
            raise ValueError('Unexpected duration')
        result.append({**row, 'source': row.get('source', 'https://commons.wikimedia.org/wiki/File:' + urllib.parse.quote(row['file'].replace(' ', '_'))),
            'acquiredFrom': download, 'duration': round(duration), 'bytes': dest.stat().st_size, 'retrieved': '2026-10-13',
            'sourceSha256': hashlib.sha256(raw.read_bytes()).hexdigest(), 'sha256': hashlib.sha256(dest.read_bytes()).hexdigest(),
            'changes': 'Chuyển sang AAC 96 kb/s để nghe ngoại tuyến; không cắt nội dung. Bản chuyển đổi giữ giấy phép của bản thu gốc.'})
        print(row['id'], round(duration), dest.stat().st_size, flush=True)
        (DATA / 'music.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
        time.sleep(3)
(DATA / 'music.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
(DATA / 'musicAssets.ts').write_text('// Generated by scripts/import_education_music.py. Offline recordings.\nexport const musicAssets: Record<string, number> = {\n' + ''.join(f"  '{r['id']}': require('../../../assets/education/{r['id']}.m4a'),\n" for r in rows) + '};\n')
