/* Offline build preparation only. Reads the response JSON, never request headers.
 * Usage: node scripts/import_pregnancy_visuals.cjs /path/to/request.txt
 * Fetches only the supplied static JPEGs; no account, API or 3D archive request.
 */
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const { execFileSync } = require("node:child_process");
const root = path.resolve(__dirname, "..");
const raw = fs.readFileSync(process.argv[2], "utf8");
const data = JSON.parse(raw.slice(raw.indexOf("{")));
const articles = require("../src/data/pregnancy/articles.json");
const dest = path.join(root, "assets/pregnancy-visuals");
fs.mkdirSync(dest, { recursive: true });
const hash = (bytes) => crypto.createHash("sha256").update(bytes).digest("hex");
const visuals = {};
for (const entry of data.visuals) {
  if (!/^week_([1-9]|[1-3]\d|40)$/.test(entry.id))
    throw new Error("Unexpected visual ID");
  const url = new URL(entry.image);
  if (
    url.protocol !== "https:" ||
    url.hostname !== "content.owhealth.com" ||
    url.search ||
    !url.pathname.endsWith(".jpg")
  )
    throw new Error("Unexpected image URL");
  const filename = entry.id + ".jpg",
    file = path.join(dest, filename);
  if (!fs.existsSync(file)) {
    const bytes = execFileSync(
      "curl",
      [
        "--fail",
        "--silent",
        "--show-error",
        "--max-time",
        "45",
        "--max-filesize",
        "8388608",
        url.href,
      ],
      { maxBuffer: 8 * 1024 * 1024 },
    );
    if (bytes[0] !== 0xff || bytes[1] !== 0xd8)
      throw new Error("Expected JPEG");
    fs.writeFileSync(file, bytes);
  }
  const {
    streams: [size],
  } = JSON.parse(
    execFileSync(
      "ffprobe",
      [
        "-v",
        "error",
        "-select_streams",
        "v:0",
        "-show_entries",
        "stream=width,height",
        "-of",
        "json",
        file,
      ],
      { encoding: "utf8" },
    ),
  );
  visuals[entry.id] = {
    file: filename,
    width: size.width,
    height: size.height,
    source: url.href,
    sha256: hash(fs.readFileSync(file)),
  };
  console.log("Imported", entry.id, size.width, size.height);
}
const weeks = data.weeks.map((w) => {
  const article = articles.find(
    (a) => a.section === "growth" && a.id === w.details.cards.baby,
  );
  if (
    !article ||
    article.week !== w.week_number - 1 ||
    !visuals[w.details.visuals.baby]
  )
    throw new Error("Unverified week mapping");
  return {
    completedWeek: article.week,
    sourceWeek: w.week_number,
    visualId: w.details.visuals.baby,
    articleId: article.id,
  };
});
if (weeks.length !== 43 || Object.keys(visuals).length !== 40)
  throw new Error("Incomplete visual set");
fs.writeFileSync(
  path.join(root, "src/data/pregnancy/visuals.json"),
  JSON.stringify(
    {
      source: "User-provided response in request(7).txt; headers excluded",
      weeks,
      visuals,
    },
    null,
    2,
  ) + "\n",
);
fs.writeFileSync(
  path.join(root, "src/data/pregnancy/visualSources.ts"),
  "// Static offline assets. Generated by import_pregnancy_visuals.cjs.\nexport const pregnancyVisualSources: Record<string, number> = {\n" +
    Object.keys(visuals)
      .map(
        (id) =>
          `  ${JSON.stringify(id)}: require("../../../assets/pregnancy-visuals/${visuals[id].file}"),`,
      )
      .join("\n") +
    "\n};\n",
);
